// Builds scripts/verify-00014-noop.sql from 00014 itself, so the checked
// statement cannot drift from the migration being tested. Verification that
// quotes the migration by hand is worthless.
import fs from 'node:fs'
import path from 'node:path'

const file = fs.readdirSync('supabase/migrations').find((f) => f.startsWith('00014'))
const migration = fs.readFileSync(path.join('supabase/migrations', file), 'utf8')

const values = migration.match(/insert into public\.taxonomic_orders[\s\S]*?on conflict \(name\) do nothing;/i)
if (!values) {
  console.error('could not find the orders insert in', file)
  process.exit(1)
}

const body = values[0].replace(/\r\n/g, '\n')
const orders = [...body.matchAll(/\(\s*'([^']*)',\s*'([^']*)',\s*\n?\s*'((?:[^']|'')*)'\s*\)/g)]
console.log(`parsed ${orders.length} orders from ${file}`)

if (orders.length !== 20) {
  console.error(`expected 20 orders, parsed ${orders.length}`)
  process.exit(1)
}

const sql = `-- Generated by scripts/build-noop-check.mjs from ${file}. Do not edit by hand.
--
-- Confirms 00014 is a safe no-op on the current live database.
--
-- 00014 inserts 20 orders with generated uuid primary keys and
-- \`on conflict (name) do nothing\`. The conflict target is \`name\`, not \`id\`,
-- so a re-run must match on the unique name index, skip every row, and leave
-- existing ids alone. Running it in a transaction and rolling back proves that
-- without writing anything.
--
-- Paste into the Supabase SQL editor. Expect: NO-OP-OK

begin;

create temporary table orders_before as
  select id, name from public.taxonomic_orders;

${body}

-- A correct no-op: nothing added, no id changed.
select
  count(*) filter (where b.id is null) as rows_added,
  count(*) filter (where b.id is distinct from a.id) as ids_changed,
  (select count(*) from public.taxonomic_orders) as orders_now,
  case
    when count(*) filter (where b.id is null) = 0
     and count(*) filter (where b.id is distinct from a.id) = 0
    then 'NO-OP-OK'
    else 'MIGRATED - inspect before committing'
  end as verdict
from orders_before b
full join public.taxonomic_orders a on a.name = b.name;

rollback;

select 'rolled back; live data unchanged' as note;
`

fs.mkdirSync('scripts', { recursive: true })
fs.writeFileSync('scripts/verify-00014-noop.sql', sql)
console.log('wrote scripts/verify-00014-noop.sql')